        <section>
            <h2>3. المتطلبات التقنية الرئيسية</h2>

            <h3>3.1 المحرك والرسوميات</h3>
            <ul>
                <li>استخدام محرك حديث مع توصية أولية بـ <strong>Unity (URP/HDRP)</strong> أو <strong>Unreal Engine 5</strong>، مع دراسة مقارنة نهائية قبل بدء الإنتاج.</li>
                <li>دعم الإضاءة الديناميكية الحقيقية (Real-time Dynamic Lighting) مع قياس المسافات (Ray Tracing اختياري للأجهزة الرائدة فقط).</li>
                <li>محاكاة فيزياء واقعية للرصاص، الارتداد، الاصطدامات، وتدمير بيئي محدود.</li>
                <li>نظام مستويات تفاصيل متعدد (LOD) لضمان الأداء على الأجهزة الضعيفة.</li>
            </ul>

            <h3>3.2 البنية التحتية والشبكات</h3>
            <ul>
                <li>نظام مزامنة سحابي يدعم آلاف اللاعبين المتزامنين، عبر خدمات مثل <strong>Photon</strong> أو <strong>Agones/Kubernetes</strong>.</li>
                <li>خوارزميات تنبؤ وحركة (Client Prediction + Server Reconciliation) لتقليل الإحساس بالتأخير.</li>
                <li>تعويض التأخير على الخادم (Lag Compensation) لضمان عدالة المبارزات.</li>
                <li>نواقل مناطق (Regional Servers) لتقليل زمن الاستجابة جغرافياً.</li>
            </ul>

            <h3>3.3 الذكاء الاصطناعي للأعداء</h3>
            <ul>
                <li>نظام سلوكي متعدد المستويات (Behavior Trees + GOAP) يشمل: التخفي، الالتفاف، طلب الدعم، وردود الفعل التكيفية.</li>
                <li>مستويات صعوبة متدرجة تتعلم من أسلوب اللاعب وتعدل التحدي تلقائياً.</li>
                <li>تنقل ذكي عبر شبكة الملاحة (NavMesh) مع استغلال البيئة (الغطاء، الارتفاعات).</li>
            </ul>
        </section>

        <section>
            <h2>4. المتطلبات غير الوظيفية</h2>
            <ul>
                <li><strong>الحد الأدنى للأجهزة:</strong> أندرويد 10 أو أحدث، ذاكرة 4 جيجابايت، معالج رسومي يدعم Vulkan.</li>
                <li><strong>الأمان:</strong> حماية من الغش (Anti-Cheat) والتشفير الكامل للاتصالات.</li>
                <li><strong>الوصولية:</strong> دعم أحجام الخطوط القابلة للتعديل، وأنماط تحكم بديلة للمستخدمين ذوي الاحتياجات الخاصة.</li>
                <li><strong>اللغات:</strong> واجهة عربية كاملة (RTL) مع دعم الإنجليزية كمرحلة أولى للتوسع.</li>
            </ul>
        </section>

        <section>
            <h2>5. نموذج الربح والتوزيع</h2>
