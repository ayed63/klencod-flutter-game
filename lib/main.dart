            <h2>1. نظرة عامة على المشروع</h2>
            <p><strong>الاسم المؤقت:</strong> (يُحدد لاحقاً)</p>
            <p>
                <strong>الهدف:</strong> تطوير لعبة تصويب تكتيكية (Tactical FPS) لأجهزة الأندرويد، تقدم تجربة قتال
                واقعية وعالية الدقة تنافس أفضل الألعاب المتاحة على المنصة، مع تحسين كامل لأداء الأجهزة المحمولة.
            </p>
            <p>
                <strong>مستوى الجودة المرجعي:</strong> تُقاس الجودة بمؤشرات قابلة للقياس (معدل الإطارات، زمن الاستجابة،
                دقة الإدخال) بدلاً من المقارنة المباشرة بألعاب المنصات المنزلية، لاختلاف قدرات العتاد جذرياً.
            </p>
        </section>

        <section>
            <h2>2. المؤشرات القابلة للقياس (KPIs)</h2>
